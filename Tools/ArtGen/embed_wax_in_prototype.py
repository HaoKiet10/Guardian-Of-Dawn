#!/usr/bin/env python3
"""Put the real Dị Thể Sáp sprites, VFX, skills, bosses and a check panel into
the HTML map prototype (Docs/Final Project/Guardian of Dawn - Map Prototype.html).

What it embeds (one block right before </body>, between the WAX-PATCH markers):
- <style>   : wax_prototype/style.css
- <script>  : window.WAXDATA = the 16 creature atlases (S row of every sheet in
              Assets/Art/Wax, one row per animation, downscaled, WebP) + every
              effect of Assets/Art/VFX (WebP) + the two manifests, trimmed
- <script>  : wax_prototype/runtime.js

The prototype's own code is NOT edited: runtime.js runs after the main script
and wraps its global functions (updateEnemies, drawEnemy, damage, kill,
drawGroundFX, drawAirFX, seedEnemies, newEnemy, resetFX, selectMap, drawTower,
updateWallGuns, TWB.*). So the patch survives a new upstream prototype as long
as those names stay; the script warns when one is missing.

Run again after re-generating sheets or pulling a new prototype; idempotent.
  python3 Tools/ArtGen/embed_wax_in_prototype.py [--html PATH] [--scale 0.75] [--quality 86] [--remove]
"""
import argparse
import base64
import io
import json
import os
import re
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
HTML = os.path.join(ROOT, "Docs", "Final Project", "Guardian of Dawn - Map Prototype.html")
WAX = os.path.join(ROOT, "Assets", "Art", "Wax")
VFX = os.path.join(ROOT, "Assets", "Art", "VFX")
SRC = os.path.join(HERE, "wax_prototype")

BEGIN = "<!-- WAX-PATCH:BEGIN (generated by Tools/ArtGen/embed_wax_in_prototype.py, do not edit by hand) -->"
END = "<!-- WAX-PATCH:END -->"
BLOCK_RE = re.compile(r"<!-- WAX-PATCH:BEGIN.*?<!-- WAX-PATCH:END -->\n", re.S)
CHARSET = '<meta charset="utf-8"><!-- WAX-PATCH:CHARSET -->\n'

# manifest name -> key used by runtime.js
KEYS = {"Standard": "standard", "Shard": "shard", "Crab": "crab", "Tiger": "tiger", "TigerCub": "cub",
        "Healer": "healer", "Spore": "spore", "Lens": "lens", "Mirror": "mirror", "Ultimate": "ultimate",
        "Frenzy": "frenzy", "Primordial": "primordial", "AlphaTiger": "alpha", "MotherTree": "mother",
        "Prism": "prism", "Myriad": "myriad"}
# globals of the prototype that runtime.js hooks into (only checked, to warn early)
HOOKS = ["function updateEnemies(", "function drawEnemy(", "function damage(", "function kill(",
         "function drawGroundFX(", "function drawAirFX(", "function seedEnemies(", "function newEnemy(",
         "function resetFX(", "function selectMap(", "function liveEnemies(", "function pos(",
         "function drawTower(", "function updateWallGuns(", "function twPt(", "function twHead(", "const TWB="]


def webp_uri(im, quality, lossless=False):
    bio = io.BytesIO()
    if lossless:
        im.save(bio, "WEBP", lossless=True, method=4)
    else:
        im.save(bio, "WEBP", quality=quality, alpha_quality=100, method=4)
    return "data:image/webp;base64," + base64.b64encode(bio.getvalue()).decode("ascii"), len(bio.getvalue())


def pack_units(scale, quality):
    man = json.load(open(os.path.join(WAX, "anim_manifest.json"), encoding="utf8"))
    out, total = {}, 0
    for name, c in man["creatures"].items():
        key = KEYS.get(name)
        if not key:
            print("  ! creature not known to runtime.js, skipped:", name)
            continue
        cell = c["cell"]
        ce = int(round(cell * scale))
        row = c["rows"].index("S")
        anims = c["anims"]
        atlas = Image.new("RGBA", (max(a["frames"] for a in anims.values()) * ce, len(anims) * ce), (0, 0, 0, 0))
        meta = {}
        for r, (an, a) in enumerate(anims.items()):
            sheet = Image.open(os.path.join(WAX, a["file"])).convert("RGBA")
            for f in range(a["frames"]):
                fr = sheet.crop((f * cell, row * cell, (f + 1) * cell, (row + 1) * cell))
                if ce != cell:
                    fr = fr.resize((ce, ce), Image.LANCZOS)
                atlas.paste(fr, (f * ce, r * ce))
            imp = a.get("impact_frame")
            meta[an] = {"r": r, "n": a["frames"], "fps": a["fps"], "loop": 1 if a["loop"] else 0,
                        "imp": -1 if imp is None else imp}
        uri, n = webp_uri(atlas, quality)
        total += n
        out[key] = {"cell": cell, "ce": ce, "h": c["height_px"], "px": c["pivot"][0], "py": c["pivot"][1],
                    "anims": meta, "img": uri}
    return out, total


def pack_vfx(scale, quality):
    man = json.load(open(os.path.join(VFX, "vfx_manifest.json"), encoding="utf8"))
    out, total = {}, 0
    for e in man["effects"]:
        name = e["name"][4:] if e["name"].startswith("vfx_") else e["name"]
        w, h = e["cell"]
        n = e["frames"]
        sheet = Image.open(os.path.join(ROOT, e["file"])).convert("RGBA")
        # small cells (icons, drips, bars) stay at full size, they are drawn close to 1:1
        sc = 1.0 if (w <= 64 or name in ("status_icons", "lens_charge_bar")) else scale
        we, he = max(1, int(round(w * sc))), max(1, int(round(h * sc)))
        if sc != 1.0:
            strip = Image.new("RGBA", (we * n, he), (0, 0, 0, 0))
            for f in range(n):
                strip.paste(sheet.crop((f * w, 0, (f + 1) * w, h)).resize((we, he), Image.LANCZOS), (f * we, 0))
        else:
            strip = sheet.crop((0, 0, w * n, h))
        uri, nb = webp_uri(strip, max(quality, 90))
        total += nb
        out[name] = {"w": w, "h": h, "we": we, "he": he, "n": n, "fps": e["fps"], "loop": 1 if e["loop"] else 0,
                     "ax": e["anchor_px"][0], "ay": e["anchor_px"][1], "add": 1 if e["blend"] == "additive" else 0,
                     "layer": e["layer"], "tint": 1 if e["tintable"] else 0, "img": uri}
    return out, man["status_icon_frames"], total


def build_block(scale, quality):
    units, nu = pack_units(scale, quality)
    vfx, icons, nv = pack_vfx(scale, quality)
    data = {"scale": scale, "units": units, "vfx": vfx, "icons": icons}
    css = open(os.path.join(SRC, "style.css"), encoding="utf8").read().strip()
    js = open(os.path.join(SRC, "runtime.js"), encoding="utf8").read().strip()
    for part in (css, js):
        if "</script" in part.lower() or "</style" in part.lower():
            sys.exit("runtime.js / style.css must not contain a closing script or style tag")
    block = (BEGIN + "\n<style id=\"wax-style\">\n" + css + "\n</style>\n"
             "<script id=\"wax-data\">window.WAXDATA=" + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";</script>\n"
             "<script id=\"wax-runtime\">\n" + js + "\n</script>\n" + END)
    print("  creatures: %d atlases, %.2f MB   vfx: %d sheets, %.2f MB" % (len(units), nu / 1e6, len(vfx), nv / 1e6))
    return block


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--html", default=HTML)
    ap.add_argument("--scale", type=float, default=0.75, help="embedded size of the sprites, relative to the source sheets")
    ap.add_argument("--quality", type=int, default=86, help="WebP quality of the creature atlases")
    ap.add_argument("--remove", action="store_true", help="only strip the patch (back to the upstream file)")
    a = ap.parse_args()

    html = open(a.html, encoding="utf8").read()
    before = len(html.encode("utf8"))
    html, removed = BLOCK_RE.subn("", html)
    html = html.replace(CHARSET, "")
    if "WAX-SPRITES:BEGIN" in html:
        sys.exit("this HTML still carries the OLD inline wax patch (WAX-SPRITES markers); start from the upstream file")
    if a.remove:
        open(a.html, "w", encoding="utf8").write(html)
        print("patch removed" if removed else "no patch found", "- %.2f MB" % (len(html.encode("utf8")) / 1e6))
        return
    missing = [h for h in HOOKS if h not in html]
    if missing:
        print("  ! the prototype no longer has: " + ", ".join(missing))
        print("    runtime.js skips what it cannot hook; check Tools/ArtGen/wax_prototype/runtime.js")
    # after the prototype's own script: before </body> (or </html>) when present, else at the end of the file
    i = max(html.rfind("</body>"), -1)
    if i < 0:
        i = html.rfind("</html>")
    if i < 0:
        i = len(html)
    if html.rfind("</script>") > i:
        sys.exit("unexpected layout: a script follows </body> in " + a.html)
    block = build_block(a.scale, a.quality)
    html = html[:i] + ("" if i == 0 or html[i - 1] == "\n" else "\n") + block + "\n" + html[i:]
    # The upstream file declares no encoding; served by a plain HTTP server (no charset header) the
    # browser falls back to Windows-1252 and every Vietnamese label turns into mojibake.
    if not re.search(r"<meta[^>]+charset", html[:1024], re.I):
        html = CHARSET + html
    open(a.html, "w", encoding="utf8").write(html)
    after = len(html.encode("utf8"))
    print("%s: %.2f MB -> %.2f MB (%s)" % (os.path.basename(a.html), before / 1e6, after / 1e6,
                                         "patch replaced" if removed else "patch added"))


if __name__ == "__main__":
    main()
